#!/usr/bin/env python3
"""Regenerates TECH_DATA in src/09d_research.js from tools/techtree.json (dumped from SerpuloTechTree, see tools/MapExport.java)."""
import json, os, re
D = os.path.dirname(__file__)
t = json.load(open(os.path.join(D, 'techtree.json'))); l = json.load(open(os.path.join(D, 'lite_names.json')))
items = {'copper', 'lead', 'metaglass', 'graphite', 'sand', 'coal', 'titanium', 'scrap', 'silicon', 'thorium', 'plastanium', 'spore-pod',
         'pyratite', 'blast-compound', 'surge-alloy', 'phase-fabric', 'water', 'cryofluid', 'oil', 'slag'}
lite = {x.split(':')[0] for x in l['blocks']} | set(l['units']) | items | {'core-shard'}
sectors = {n['name'] for n in t if n['type'] == 'sector'}
by = {n['name']: n for n in t}
def anc(p):
    while p and p not in lite: p = by[p]['parent']
    return p
rows = []
for n in t:
    if n['type'] == 'sector' or n['name'] not in lite or n['name'] == 'core-shard': continue
    req = ' '.join(f"{i}:{a}" for i, a in n['req']) if n['type'] in ('block', 'unit') else ''
    reqitems = {i for i, a in n['req']}
    obj = []
    for o in n['obj']:
        k, _, v = o.partition(':')
        if k == 'research' and v in lite and v not in reqitems: obj.append(v)
        elif k in ('sector', 'on') and v in sectors: obj.append(o)
    rows.append([n['name'], n['type'][0], anc(n['parent']), req, ' '.join(obj)])
out = ("// Generated by tools/gen_techtree.py from SerpuloTechTree (TechNode requirements and objectives).\n"
       "// [name, type (b block, u unit, i item, l liquid), parent, research cost, objectives: content to research / obtain,\n"
       "//  sector:<name> = sector captured, on:<name> = playing that sector]\nconst TECH_DATA = [\n" +
       ''.join('  ' + json.dumps(r) + ',\n' for r in rows) + "];\n")
p = os.path.join(D, '..', 'src', '09d_research.js')
s = open(p).read()
i = s.index('// Generated'); j = s.index('];\n', s.index('const TECH_DATA')) + 3
open(p, 'w').write(s[:i] + out + s[j:])
print(len(rows), 'nodes;', sum(1 for r in rows if 'sector:' in r[4] or 'on:' in r[4]), 'with sector objectives')
